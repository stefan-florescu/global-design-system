// Bundles server/edge.ts into the price-tracker Edge Function (ADR 0011). Supabase runs it on
// Deno, which loads supabase-js from npm; everything else (the app's parsing, matching and
// change-detection code) is bundled in.
import { build } from "esbuild";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

await build({
  entryPoints: [join(root, "server/edge.ts")],
  tsconfig: join(root, "tsconfig.json"),
  outfile: join(root, "supabase/functions/price-tracker/index.ts"),
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2022",
  legalComments: "none",
  minifyWhitespace: true,
  minifySyntax: true,
  banner: {
    js: "// @ts-nocheck\n// Generated by scripts/build-function.mjs from server/edge.ts. Do not edit.",
  },
  plugins: [
    {
      name: "deno-npm",
      setup(b) {
        b.onResolve({ filter: /^@supabase\/supabase-js$/ }, () => ({
          path: "npm:@supabase/supabase-js@2",
          external: true,
        }));
      },
    },
  ],
});

console.log("Built supabase/functions/price-tracker/index.ts");
